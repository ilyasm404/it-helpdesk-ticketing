package com.helpdesk.dao;

import com.helpdesk.db.DataAccessException;
import com.helpdesk.db.Database;
import com.helpdesk.model.Priority;
import com.helpdesk.model.Status;
import com.helpdesk.model.Ticket;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/** CRUD and search operations for tickets. */
public class TicketDao {

    public Ticket create(Ticket t) {
        String sql = "INSERT INTO tickets (title, description, priority, status, created_by, assigned_to) "
                + "VALUES (?, ?, ?, ?, ?, ?)";
        try (Connection c = Database.getConnection();
             PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, t.getTitle());
            ps.setString(2, t.getDescription());
            ps.setString(3, t.getPriority().name());
            ps.setString(4, t.getStatus().name());
            ps.setInt(5, t.getCreatedBy());
            setNullableInt(ps, 6, t.getAssignedTo());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    t.setId(keys.getInt(1));
                }
            }
            // Re-read so timestamps generated by MySQL are populated.
            return findById(t.getId()).orElse(t);
        } catch (SQLException e) {
            throw new DataAccessException("Could not create ticket: " + e.getMessage(), e);
        }
    }

    public Optional<Ticket> findById(int id) {
        String sql = "SELECT * FROM tickets WHERE id = ?";
        try (Connection c = Database.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(map(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw new DataAccessException("Could not load ticket: " + e.getMessage(), e);
        }
    }

    public List<Ticket> findAll() {
        return search(new TicketFilter());
    }

    /** Builds a WHERE clause from whichever filter fields are set. Highest priority first. */
    public List<Ticket> search(TicketFilter f) {
        StringBuilder sql = new StringBuilder("SELECT * FROM tickets WHERE 1=1");
        List<Object> params = new ArrayList<>();

        if (f.getStatus() != null) {
            sql.append(" AND status = ?");
            params.add(f.getStatus().name());
        }
        if (f.getPriority() != null) {
            sql.append(" AND priority = ?");
            params.add(f.getPriority().name());
        }
        if (f.isUnassignedOnly()) {
            sql.append(" AND assigned_to IS NULL");
        } else if (f.getAssignedTo() != null) {
            sql.append(" AND assigned_to = ?");
            params.add(f.getAssignedTo());
        }
        if (f.getCreatedBy() != null) {
            sql.append(" AND created_by = ?");
            params.add(f.getCreatedBy());
        }
        if (f.getKeyword() != null && !f.getKeyword().isBlank()) {
            sql.append(" AND (title LIKE ? OR description LIKE ?)");
            String like = "%" + f.getKeyword().trim() + "%";
            params.add(like);
            params.add(like);
        }
        sql.append(" ORDER BY FIELD(priority, 'CRITICAL', 'HIGH', 'MEDIUM', 'LOW'), created_at");

        List<Ticket> tickets = new ArrayList<>();
        try (Connection c = Database.getConnection();
             PreparedStatement ps = c.prepareStatement(sql.toString())) {
            for (int i = 0; i < params.size(); i++) {
                ps.setObject(i + 1, params.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    tickets.add(map(rs));
                }
            }
        } catch (SQLException e) {
            throw new DataAccessException("Could not search tickets: " + e.getMessage(), e);
        }
        return tickets;
    }

    public boolean update(Ticket t) {
        String sql = "UPDATE tickets SET title = ?, description = ?, priority = ?, status = ?, "
                + "assigned_to = ? WHERE id = ?";
        try (Connection c = Database.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, t.getTitle());
            ps.setString(2, t.getDescription());
            ps.setString(3, t.getPriority().name());
            ps.setString(4, t.getStatus().name());
            setNullableInt(ps, 5, t.getAssignedTo());
            ps.setInt(6, t.getId());
            return ps.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DataAccessException("Could not update ticket: " + e.getMessage(), e);
        }
    }

    public boolean delete(int id) {
        String sql = "DELETE FROM tickets WHERE id = ?";
        try (Connection c = Database.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setInt(1, id);
            return ps.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DataAccessException("Could not delete ticket: " + e.getMessage(), e);
        }
    }

    private static void setNullableInt(PreparedStatement ps, int index, Integer value) throws SQLException {
        if (value == null) {
            ps.setNull(index, Types.INTEGER);
        } else {
            ps.setInt(index, value);
        }
    }

    private Ticket map(ResultSet rs) throws SQLException {
        int assigned = rs.getInt("assigned_to");
        Integer assignedTo = rs.wasNull() ? null : assigned;
        return new Ticket(
                rs.getInt("id"),
                rs.getString("title"),
                rs.getString("description"),
                Priority.valueOf(rs.getString("priority")),
                Status.valueOf(rs.getString("status")),
                rs.getInt("created_by"),
                assignedTo,
                rs.getTimestamp("created_at").toLocalDateTime(),
                rs.getTimestamp("updated_at").toLocalDateTime());
    }
}
